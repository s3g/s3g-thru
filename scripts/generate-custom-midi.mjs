import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const model=JSON.parse(fs.readFileSync(path.join(root,'controllers/korg-nanokontrol2/profile.json'),'utf8'));
const registry=JSON.parse(fs.readFileSync(path.join(root,'controllers/midi/parameters.json'),'utf8')).parameters;
const byKey=new Map(registry.map(p=>[p.key,p]));
const commands=['play','stop','record','undo','panic','previousBank','nextBank',...Array.from({length:8},(_,i)=>'bank'+(i+1)),'takeUndo','previousClip','nextClip','patternHold','ignore'];
assert(model.version===1&&model.bindings.length<=128);
const seen=new Set(),lines=[];
for(const [i,e]of model.bindings.entries()){
    assert(Number.isInteger(e.channel)&&e.channel>=1&&e.channel<=16&&Number.isInteger(e.cc)&&e.cc>=0&&e.cc<=127);
    assert(Number.isInteger(e.bank)&&e.bank>=0&&e.bank<=8);
    const key=e.channel+':'+e.cc+':'+e.bank;assert(!seen.has(key),'Duplicate '+key);seen.add(key);
    let kind=0,target=-1,part=({Global:-1,A:0,B:1,C:2,D:3,Focus:4})[e.part];
    assert(Number.isInteger(part));
    if(e.kind==='parameter'){
        const p=byKey.get(e.parameter);assert(p,'Unknown parameter '+e.parameter);target=p.id;
        assert(p.scope==='part'?part>=0:part===-1);
    }else if(e.kind==='engine'){
        kind=1;assert(e.page>=0&&e.page<=3&&e.slot>=0&&e.slot<=7&&part>=0);
    }else{assert(e.kind==='command');kind=2;target=commands.indexOf(e.target);assert(target>=0&&e.behavior===3);}
    lines.push(`    {auto& b=p.bindings[${i}];b.enabled=1;b.channel=${e.channel};b.cc=${e.cc};b.bank=${e.bank};b.part=${part};b.kind=${kind};b.target=${target};b.page=${e.page||0};b.slot=${e.slot||0};b.behavior=${e.behavior||0};}`);
}
const result=`// Generated by scripts/generate-custom-midi.mjs from the public controller profile.\n#pragma once\n#include "thru_midi_custom.h"\nnamespace s3g_thru_custom_midi {\ninline Profile nanoProfile() {\n    Profile p;\n${lines.join('\n')}\n    return p;\n}\n}\n`;
const filename=path.join(root,'include/thru_nano_profile.h');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(filename,'utf8'),result,'nanoKONTROL2 starter is stale');
else fs.writeFileSync(filename,result);
console.log(`s3g Thru Custom MIDI starter: PASS (${model.bindings.length} nanoKONTROL2 bindings, eight banks)`);
