import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'controllers/midi/parameters.json')));
const ids = new Set(), keys = new Set();
assert.equal(registry.version, 1);
for (const p of registry.parameters) {
    assert(Number.isInteger(p.id) && p.id >= 0 && p.id < 16383);
    assert(!ids.has(p.id) && !keys.has(p.key), `Duplicate MIDI parameter ${p.key}`);
    ids.add(p.id); keys.add(p.key);
    assert(/^[a-z][a-z0-9_]*$/.test(p.key));
    assert(['part', 'global'].includes(p.scope));
    assert(Number.isFinite(p.min) && Number.isFinite(p.max) && p.min < p.max, p.key);
    assert(p.default >= p.min && p.default <= p.max, p.key);
    assert(!p.curve || p.curve==='log' && p.min>0, 'Invalid MIDI curve: '+p.key);
}
for(const id of registry.reserved_ids || []) {
    assert(Number.isInteger(id) && id >= 0 && id < 16383 && !ids.has(id), 'Reserved MIDI ID reused: '+id);
}
const parameters = [...registry.parameters].sort((a, b) => a.id - b.id);
const startupFeedback = registry.startup_feedback.map(({part, key}) => {
    const p = parameters.find(p => p.key === key);
    assert(p && !p.action && Number.isInteger(part), 'Invalid startup feedback: '+key);
    assert(p.scope === 'part' ? part >= 0 && part < registry.part_channels.length : part === -1,
        'Invalid startup feedback scope: '+key);
    return {part, id:p.id};
});
assert.equal(new Set(startupFeedback.map(p => p.part+':'+p.id)).size, startupFeedback.length,
    'Repeated startup feedback subscription');
const f = (n) => `${Number.isInteger(n) ? n + '.0' : n}f`;
const cppSource=fs.readFileSync(path.join(root,'src/dsp/thru_module.cpp'),'utf8');
const lockBody=cppSource.match(/constexpr const char\* kLockParameterKeys\[kLockParameterCount\] \{([\s\S]*?)\n\};/)[1];
const lockKeys=[...lockBody.matchAll(/"([^"]+)"/g)].map(m=>m[1]);
for(const key of lockKeys)assert(keys.has(key),'Unmapped engine parameter '+key);
const rows = parameters.map((p) => `    {${p.id}, ${JSON.stringify(p.key)}, ${f(p.min)}, ${f(p.max)}, ${f(p.default)}, ${p.scope === 'part'}, ${p.integer}, ${p.action}, ${p.curve==='log'}, ${lockKeys.indexOf(p.key)}},`);
const header = `// Generated by scripts/generate-midi.mjs; edit controllers/midi/parameters.json.\n` +
`#ifndef S3G_THRU_MIDI_PARAMETERS_H\n#define S3G_THRU_MIDI_PARAMETERS_H\n` +
`#include <cstddef>\n#include <cstdint>\n#include <cmath>\n#include <algorithm>\n` +
`namespace s3g_thru_midi {\n` +
`struct Parameter {int id; const char* key; float minimum, maximum, initial; bool part, integer, action, logarithmic; int lock;};\n` +
`inline constexpr Parameter parameters[]{\n${rows.join('\n')}\n};\n` +
`inline constexpr std::size_t count = sizeof(parameters) / sizeof(parameters[0]);\n` +
`struct FeedbackSubscription {int part,id;};\n` +
`inline constexpr FeedbackSubscription startupFeedback[]{\n${startupFeedback.map(p => `    {${p.part},${p.id}},`).join('\n')}\n};\n` +
`inline const Parameter* find(int id) {\n` +
`    std::size_t first=0, last=count;\n` +
`    while(first<last) {const auto mid=(first+last)/2; if(parameters[mid].id<id)first=mid+1;else last=mid;}\n` +
`    return first<count && parameters[first].id==id ? &parameters[first] : nullptr;\n}\n` +
`inline int encode(const Parameter& p, float value, float maximum) {\n` +
`    if(maximum<=p.minimum)return 0;\n` +
`    const float unit=std::clamp(p.logarithmic ? std::log(std::clamp(value,p.minimum,maximum)/p.minimum)/std::log(maximum/p.minimum) : (value-p.minimum)/(maximum-p.minimum),0.0f,1.0f);\n` +
`    return static_cast<int>(std::lround(unit*16383.0f));\n}\n` +
`inline float decode(const Parameter& p,int raw,float maximum) {\n` +
`    if(maximum<=p.minimum)return p.minimum;\n` +
`    raw=std::clamp(raw,0,16383);\n` +
`    float value=raw==0?p.minimum:raw==16383?maximum:p.logarithmic ? p.minimum*std::exp(std::log(maximum/p.minimum)*(static_cast<float>(raw)/16383.0f)) : p.minimum+(maximum-p.minimum)*(static_cast<float>(raw)/16383.0f);\n` +
`    if(p.integer)return std::round(value);\n` +
`    // Preserve exact unity/default and centre values at their nearest MIDI code.\n` +
`    if(p.initial>=p.minimum && p.initial<=maximum && raw==encode(p,p.initial,maximum))return p.initial;\n` +
`    if(p.minimum<0 && maximum>0 && raw==encode(p,0,maximum))return 0;\n` +
`    return value;\n}\n}\n#endif\n`;
const compact = parameters.map(({ id, key, scope, min, max, integer, action, name, options, unit, curve, group, short_name }) =>
    ({ id, key, scope, min, max, integer, action, name, group, short_name, ...(options ? { options } : {}), ...(unit ? { unit } : {}), ...(curve ? {curve} : {}) }));
const js = `// Generated by scripts/generate-midi.mjs. Stable IDs must not be reassigned.\n` +
    `export const MIDI_PARAMETERS = ${JSON.stringify(compact)};\n` +
    `export const MIDI_BY_KEY = new Map(MIDI_PARAMETERS.map(p => [p.key,p]));\n` +
    `export const MIDI_BY_ID = new Map(MIDI_PARAMETERS.map(p => [p.id,p]));\n`;
const quote = (s) => `"${String(s ?? '').replaceAll('"', '""')}"`;
const csv = [['NRPN', 'MSB', 'LSB', 'Group', 'Parameter', 'Key', 'Channels', 'Minimum', 'Maximum', 'Curve', 'Action'],
    ...parameters.map(p => [p.id, p.id >> 7, p.id & 127, p.group, p.name, p.key,
        p.scope === 'part' ? '5 A / 6 B / 7 C / 8 D' : '16', p.min, p.max, p.curve||'linear', p.action ? 'Yes' : 'No'])]
    .map(row => row.map(quote).join(',')).join('\n') + '\n';
const outputs = new Map([['include/thru_midi_parameters.h', header],
    ['src/midi-map.mjs', js], ['controllers/midi/parameters.csv', csv]]);
const check = process.argv.includes('--check');
for (const [relative, content] of outputs) {
    const target = path.join(root, relative);
    if (check) assert.equal(fs.readFileSync(target, 'utf8'), content, `${relative} is stale`);
    else fs.writeFileSync(target, content);
}
console.log(`s3g Thru MIDI registry: PASS (${parameters.length} fixed NRPN addresses)`);
