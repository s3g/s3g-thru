import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const all=JSON.parse(fs.readFileSync(path.join(root,'controllers/midi/parameters.json'))).parameters;
const cpp=fs.readFileSync(path.join(root,'src/dsp/thru_module.cpp'),'utf8');
const body=cpp.match(/constexpr const char\* kLockParameterKeys\[kLockParameterCount\] \{([\s\S]*?)\n\};/)[1];
const keys=[...body.matchAll(/"([^"]+)"/g)].map(m=>m[1]);
const excluded=new Set(['algorithm','locus','manual_lane','lane_cycles','lane_path','lane_blend','lane_path_shape','lane_path_offset','lane_path_skew','lane_path_curve','lane_slew','lane_1_gain','lane_2_gain','lane_3_gain','lane_4_gain','formant_freeze','formant_freeze_position','stochastic_source_hold','stochastic_hold_position','pulsar_source_hold','pulsar_hold_position']);
const rows=[];
for(const p of all){
 let target=keys.indexOf(p.key),scope=0;
 if(p.id>=5000&&p.id<5032){target=704+p.id-5000;scope=1;}
 else if(p.id>=4800&&p.id<4904){target=576+p.id-4800;scope=1;}
 else if(p.id>=4600&&p.id<4632){target=544+p.id-4600;scope=1;}
 else if(p.id>=4500&&p.id<4588){target=448+p.id-4500;scope=1;}
 else if(p.id>=4400&&p.id<4432){target=384+p.id-4400;scope=1;}
 else if(p.id>=4300&&p.id<4331){target=320+p.id-4300;scope=1;}
 else if(p.id>=4200&&p.id<4240&&p.key!=='table_model'){target=256+p.id-4200;scope=1;}
 else if([6,7,8,3867,3871,3872,3873,3874].includes(p.id)){scope=2;}
 else if(p.scope==='part'&&!p.action&&target>=0&&!excluded.has(p.key))scope=p.key.startsWith('effect_')?2:1;
 if(scope)rows.push({id:p.id,key:p.key,scope:scope===1?'voice':'lane',target});
}
rows.sort((a,b)=>a.id-b.id);assert(rows.length>120);
const header=`// Generated by scripts/generate-sequence-locks.mjs. IDs are existing MIDI identities.\n#pragma once\n#include <cstdint>\nnamespace s3g_thru_sequence {\nstruct SoundDescriptor {std::uint16_t id;std::int16_t target;bool lane;};\ninline constexpr SoundDescriptor soundCatalog[]{\n${rows.map(p=>`  {${p.id},${p.target},${p.scope==='lane'}},`).join('\n')}\n};\ninline const SoundDescriptor* soundDescriptor(int id){\n int a=0,b=sizeof(soundCatalog)/sizeof(*soundCatalog);while(a<b){int m=(a+b)/2;if(soundCatalog[m].id<id)a=m+1;else b=m;}\n return a<int(sizeof(soundCatalog)/sizeof(*soundCatalog))&&soundCatalog[a].id==id?&soundCatalog[a]:nullptr;\n}\n}\n`;
const begin='/* SEQUENCE_SOUND_CATALOG_BEGIN */',end='/* SEQUENCE_SOUND_CATALOG_END */';
const uipath=path.join(root,'src/ui.js');let ui=fs.readFileSync(uipath,'utf8');
const block=begin+'\nconst SEQUENCE_SOUND_SCOPES='+JSON.stringify(Object.fromEntries(rows.map(p=>[p.id,p.scope])))+';\nconst SEQUENCE_SOUND_IDS='+JSON.stringify(Object.fromEntries(rows.map(p=>[p.key,p.id])))+';\n'+end;
if(ui.includes(begin))ui=ui.slice(0,ui.indexOf(begin))+block+ui.slice(ui.indexOf(end)+end.length);else ui=ui.replace('const LOCKABLE_KEYS = [',block+'\n\nconst LOCKABLE_KEYS = [');
for(const [name,text] of [['include/thru_sequence_lock_catalog.h',header],['controllers/midi/sequence-locks.json',JSON.stringify(rows,null,2)+'\n'],['src/ui.js',ui]]){
 const p=path.join(root,name);if(process.argv.includes('--check'))assert.equal(fs.readFileSync(p,'utf8'),text,name+' is stale');else fs.writeFileSync(p,text);
}
console.log('s3g Thru Sequence sound-lock catalog: PASS ('+rows.length+' controls, existing IDs)');
